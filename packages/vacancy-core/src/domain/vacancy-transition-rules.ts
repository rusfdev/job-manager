import {
  VACANCY_STATUS,
  VACANCY_TRANSITION,
  type VacancyStatus,
  type VacancyTransition,
} from "@repo/shared/domain";

export type VacancyTransitionRule = {
  readonly from: readonly VacancyStatus[];
  readonly to: VacancyStatus;
};

export const VACANCY_TRANSITION_RULES = {
  [VACANCY_TRANSITION.APPLY]: {
    from: [VACANCY_STATUS.NEW, VACANCY_STATUS.HIDDEN],
    to: VACANCY_STATUS.APPLIED,
  },
  [VACANCY_TRANSITION.HIDE]: {
    from: [VACANCY_STATUS.NEW],
    to: VACANCY_STATUS.HIDDEN,
  },
  [VACANCY_TRANSITION.PASS_SCREENING]: {
    from: [VACANCY_STATUS.APPLIED],
    to: VACANCY_STATUS.SCREENING_PASSED,
  },
  [VACANCY_TRANSITION.PASS_INTERVIEW]: {
    from: [VACANCY_STATUS.APPLIED, VACANCY_STATUS.SCREENING_PASSED],
    to: VACANCY_STATUS.INTERVIEW_PASSED,
  },
  [VACANCY_TRANSITION.MARK_REJECTED]: {
    from: [
      VACANCY_STATUS.APPLIED,
      VACANCY_STATUS.SCREENING_PASSED,
      VACANCY_STATUS.INTERVIEW_PASSED,
    ],
    to: VACANCY_STATUS.REJECTED,
  },
  [VACANCY_TRANSITION.RECEIVE_OFFER]: {
    from: [VACANCY_STATUS.INTERVIEW_PASSED],
    to: VACANCY_STATUS.OFFER,
  },
  [VACANCY_TRANSITION.ACCEPT_OFFER]: {
    from: [VACANCY_STATUS.OFFER],
    to: VACANCY_STATUS.ACCEPTED,
  },
  [VACANCY_TRANSITION.DECLINE_OFFER]: {
    from: [VACANCY_STATUS.OFFER],
    to: VACANCY_STATUS.OFFER_DECLINED,
  },
  [VACANCY_TRANSITION.REVOKE_OFFER]: {
    from: [VACANCY_STATUS.OFFER],
    to: VACANCY_STATUS.OFFER_REVOKED,
  },
} as const satisfies Record<VacancyTransition, VacancyTransitionRule>;
